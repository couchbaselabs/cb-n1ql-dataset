#!/usr/bin/env python3
"""
Generate .env from config.json value fields.

Usage:
    python scripts/setup.py
    make setup
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
CONFIG_FILE = ROOT_DIR / "config.json"
ENV_FILE = ROOT_DIR / ".env"


def main() -> None:
    if not CONFIG_FILE.exists():
        print(f"Error: config.json not found at {CONFIG_FILE}", file=sys.stderr)
        sys.exit(1)

    config = json.loads(CONFIG_FILE.read_text())
    groups = config["groups"]

    lines: list[str] = [
        "# .env — generated by `make setup` from config.json",
        "# Do not edit this file directly. Update values in config.json and re-run `make setup`.",
        "",
    ]

    missing_required: list[str] = []

    for group in groups:
        lines.append(f"# ── {group['name']} {'─' * max(0, 50 - len(group['name']))}")
        for var in group["variables"]:
            key = var["key"]
            value = var.get("value", "")
            lines.append(f"{key}={value}")
            if var.get("required") and not value:
                missing_required.append(key)
        lines.append("")

    ENV_FILE.write_text("\n".join(lines))
    print(f"✓ Written to {ENV_FILE}")

    if missing_required:
        print("\n⚠ The following required variables have no value in config.json:")
        for k in missing_required:
            print(f"   {k}")
        print("Set their value fields in config.json and re-run `make setup`.")


if __name__ == "__main__":
    main()
